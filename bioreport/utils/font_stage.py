"""Stage built-in fonts for HTML output and declare them via @font-face.

Fonts ship inside the package (bioreport/assets/fonts); this module copies the
weight-subset used by reports into the output folder and writes fonts.css with
relative URLs. Quarto's embed-resources then inlines the declared files into the
single-file HTML, so reports display identically on machines without the fonts.
"""
import shutil
from pathlib import Path

# Family name -> (dest file, source candidates). Only the weights the report
# CSS actually uses are staged, to keep the embedded HTML size in check.
_STAGED_FONTS = {
    "Source Sans 3": {
        400: ("SourceSans3-Regular.ttf", ["Source_Sans_3/static/SourceSans3-Regular.ttf"]),
        700: ("SourceSans3-Bold.ttf", ["Source_Sans_3/static/SourceSans3-Bold.ttf"]),
        "400i": ("SourceSans3-Italic.ttf", ["Source_Sans_3/static/SourceSans3-Italic.ttf"]),
    },
    "HarmonyOS Sans SC": {
        400: ("HarmonyOS_Sans_SC_Regular.ttf", ["HarmonyOS_Sans_SC/HarmonyOS_Sans_SC_Regular.ttf"]),
        700: ("HarmonyOS_Sans_SC_Bold.ttf", ["HarmonyOS_Sans_SC/HarmonyOS_Sans_SC_Bold.ttf"]),
    },
}

_CSS_TEMPLATE = """/* Auto-generated by BioReport: built-in fonts staged into this report folder. */
@font-face {{
  font-family: 'BioReport-Latin';
  src: url('fonts/{latin400}') format('truetype');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}}
@font-face {{
  font-family: 'BioReport-Latin';
  src: url('fonts/{latin700}') format('truetype');
  font-weight: 700;
  font-style: normal;
  font-display: swap;
}}
@font-face {{
  font-family: 'BioReport-Latin';
  src: url('fonts/{latin400i}') format('truetype');
  font-weight: 400;
  font-style: italic;
  font-display: swap;
}}
@font-face {{
  font-family: 'BioReport-CN';
  src: url('fonts/{cn400}') format('truetype');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}}
@font-face {{
  font-family: 'BioReport-CN';
  src: url('fonts/{cn700}') format('truetype');
  font-weight: 700;
  font-style: normal;
  font-display: swap;
}}

/* Latin-first stack: English and digits use Source Sans 3, CJK falls through. */
:root {{
  --bs-body-font-family: 'BioReport-Latin', 'BioReport-CN', -apple-system, BlinkMacSystemFont, sans-serif;
}}
body {{
  font-family: var(--bs-body-font-family);
}}
"""


def stage_fonts(output_dir: str | Path) -> Path | None:
    """Copy report fonts into <output>/fonts and write <output>/fonts.css.

    Returns the fonts.css path, or None when the built-in font files are
    missing (e.g. a stripped install); HTML then falls back to system fonts.
    """
    from .fonts import font_dir

    output = Path(output_dir)
    fonts_target = output / "fonts"
    sources = {}
    for family, weights in _STAGED_FONTS.items():
        for weight, (dest, candidates) in weights.items():
            source = next((font_dir() / c for c in candidates if (font_dir() / c).is_file()), None)
            if source is None:
                return None
            sources[dest] = source
    fonts_target.mkdir(parents=True, exist_ok=True)
    for dest, source in sources.items():
        shutil.copy2(source, fonts_target / dest)
    css = _CSS_TEMPLATE.format(
        latin400="SourceSans3-Regular.ttf",
        latin700="SourceSans3-Bold.ttf",
        latin400i="SourceSans3-Italic.ttf",
        cn400="HarmonyOS_Sans_SC_Regular.ttf",
        cn700="HarmonyOS_Sans_SC_Bold.ttf",
    )
    css_path = output / "fonts.css"
    css_path.write_text(css, encoding="utf-8")
    return css_path
